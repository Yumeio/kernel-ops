#!/usr/bin/env python3
"""Generate the C++ capability table from registry/capabilities/*.yaml.

The YAML files use JSON syntax (a subset of YAML 1.2) so the generator needs no
third-party parser. Each file is either a JSON object with a "rows" array or a
plain array of rows.

Usage:
    python tools/gen_registry.py -o build/generated/registry_table.inc
"""
from __future__ import annotations

import argparse
import glob
import json
import os

PROVIDERS = {
    "native": "kNative",
    "flashinfer": "kFlashInfer",
    "cutlass": "kCutlass",
    "cublaslt": "kCublasLt",
    "deepgemm": "kDeepGemm",
    "trtllm_gen": "kTrtllmGen",
    "flashmla": "kFlashMLA",
    "fla": "kFla",
    "triton": "kTriton",
    "nccl": "kNccl",
    "deepep": "kDeepEP",
    "flashattention": "kFlashAttention",
    "marlin": "kMarlin",
    "machete": "kMachete",
}
STATUS = {
    "planned": "kPlanned",
    "implemented": "kImplemented",
    "compiled": "kCompiled",
    "numerically_validated": "kNumericallyValidated",
    "benchmarked": "kBenchmarked",
    "release_supported": "kReleaseSupported",
}
STRATEGIES = {
    "modular": "kModular",
    "graph": "kGraph",
    "pdl": "kPDL",
    "persistent": "kPersistent",
    "megakernel": "kMegakernel",
}


def fnv1a64(text: str) -> int:
    h = 0x100000001B3
    for b in text.encode("utf-8"):
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h or 1


def cstr(value: object) -> str:
    s = "" if value is None else str(value)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--dir", default="registry/capabilities")
    args = ap.parse_args()

    rows = []
    for path in sorted(glob.glob(os.path.join(args.dir, "*.yaml"))):
        with open(path, "r", encoding="utf-8") as f:
            doc = json.load(f)
        entries = doc.get("rows", []) if isinstance(doc, dict) else doc
        for r in entries:
            symbol = r.get("kernel_symbol") or r.get("symbol") or "unknown"
            arch = int(r.get("arch_id", 0))
            backend = int(r.get("backend", 0))
            provider = str(r.get("provider", "native")).lower()
            status = str(r.get("status", "planned")).lower()
            strategy = str(r.get("strategy", "modular")).lower()
            canonical = f"{symbol}|{r.get('template_args', '')}|{arch}|{backend}"
            rows.append(
                {
                    "op_id": r.get("op_id", symbol),
                    "kernel_id": int(r.get("kernel_id", fnv1a64(canonical))),
                    "symbol": symbol,
                    "provider": PROVIDERS.get(provider, "kNative"),
                    "provider_commit": r.get("provider_commit", ""),
                    "backend": "kops::BackendKind::kCuda" if backend == 0 else "kops::BackendKind::kHip",
                    "arch_id": arch,
                    "toolkit": int(r.get("min_toolkit_version", 12090)),
                    "strategy": STRATEGIES.get(strategy, "kModular"),
                    "status": STATUS.get(status, "kPlanned"),
                    "predicates": r.get("predicates", ""),
                    "mutations": r.get("mutations", ""),
                    "evidence": r.get("evidence", ""),
                }
            )

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_registry.py. Do not edit.\n")
        f.write("#pragma once\n")
        f.write("static constexpr kops::registry::Capability kGeneratedCapabilities[] = {\n")
        for r in rows:
            f.write(
                "  {%s, 0x%016xull, %s, kops::registry::Provider::%s, %s, %s, %d, %d, "
                "kops::ExecutionStrategy::%s, kops::registry::CapabilityStatus::%s, %s, %s, %s},\n"
                % (
                    cstr(r["op_id"]),
                    r["kernel_id"],
                    cstr(r["symbol"]),
                    r["provider"],
                    cstr(r["provider_commit"]),
                    r["backend"],
                    r["arch_id"],
                    r["toolkit"],
                    r["strategy"],
                    r["status"],
                    cstr(r["predicates"]),
                    cstr(r["mutations"]),
                    cstr(r["evidence"]),
                )
            )
        f.write("};\n")
        f.write("static constexpr size_t kGeneratedCapabilityCount = %d;\n" % len(rows))
    print(f"registry: wrote {len(rows)} rows to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

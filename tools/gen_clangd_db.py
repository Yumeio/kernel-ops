#!/usr/bin/env python3
"""Generate build-clangd/compile_commands.json, the clangd database.

Why this exists instead of pointing clangd at CMake's database:

  * CMake emits nvcc command lines for .cu files. clangd parses with clang, so
    every nvcc-only option (-arch, -Xcompiler, --generate-code, --threads, ...)
    has to be dropped and one CUDA target selected.
  * The library headers under csrc/ contain no #include by design (AGENTS.md,
    "Header and ABI rules"). A header opened on its own therefore reports every
    type as unknown. For each header this script emits a compile command whose
    force-included prelude is the header's transitive `Requires:` closure - the
    same closure tools/header_check/check_requires.py validates in CI - so the
    header's own definitions are parsed once and all prerequisites are visible.

Usage (after every configure, and after adding/reshaping headers):

    cmake --preset dev
    python tools/gen_clangd_db.py

Outputs, both gitignored:

    build-clangd/compile_commands.json
    build-clangd/prelude/<header>.h        (generated, do not edit)

Options exist for the other presets, the CUDA toolkit and the GPU arch:

    python tools/gen_clangd_db.py --base build/bench/compile_commands.json
    python tools/gen_clangd_db.py --cuda-path "C:/Program Files/NVIDIA GPU Computing Toolkit/CUDA/v12.9" --gpu-arch sm_90a
"""
import argparse
import json
import os
import shlex
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "header_check"))
import check_requires as requires  # noqa: E402  (ORDER, closure)

TOOLKIT_INCLUDES = """\
#include <cstdint>
#include <cstddef>
#include <cuda.h>
#include <cuda_runtime.h>
#include <cuda_fp16.h>
#include <cuda_bf16.h>
#include <cuda_fp8.h>
#include <cuda_fp4.h>"""

# Arguments clangd/clang must see; everything else in the nvcc command is either
# an nvcc-only option or an output/object-file option.
KEEP_FLAGS = ("-I", "-D", "-U", "-isystem", "-iquote", "-include")


def split_command(entry):
    """Return the argv of a compile_commands.json entry (CMake writes "command")."""
    if "arguments" in entry:
        return list(entry["arguments"])
    argv = shlex.split(entry["command"], posix=False)
    return [a[1:-1] if len(a) >= 2 and a[0] == a[-1] == '"' else a for a in argv]


def keep_includes(argv):
    """Keep only the include paths and preprocessor definitions of a command."""
    kept = []
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg in KEEP_FLAGS and i + 1 < len(argv):
            kept += [arg, argv[i + 1]]
            i += 2
            continue
        if arg.startswith(KEEP_FLAGS) or any(
                arg.startswith(flag + "=") for flag in KEEP_FLAGS):
            kept.append(arg)
        i += 1
    return kept


def clang_command(clang, cuda_path, gpu_arch, extra, source):
    return [
        clang,
        "-xcuda",
        f"--cuda-path={cuda_path}",
        f"--cuda-gpu-arch={gpu_arch}",
        "--no-cuda-version-check",
        "-std=c++17",
        "-Wno-unknown-cuda-version",
        "-Wno-pragma-once-outside-header",
        "-Xclang",
        "-fcuda-allow-variadic-functions",
        "-fsyntax-only",
        "-I",
        str(ROOT),
        *extra,
        str(source),
    ]


def prelude_name(header):
    return header.replace("/", "__").replace(".", "_") + ".h"


def write_prelude(prelude_dir, header, deps):
    body = [
        "// Generated by tools/gen_clangd_db.py - do not edit.",
        f"// Prerequisite closure of csrc/{header}.",
        "// Mirrors the Requires: comments validated by",
        "// tools/header_check/check_requires.py - keep those comments accurate.",
        "#pragma once",
        "",
        TOOLKIT_INCLUDES,
        "",
    ]
    body += [f'#include "csrc/{dep}"' for dep in deps]
    path = prelude_dir / prelude_name(header)
    path.write_text("\n".join(body) + "\n")
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--base", default="build/dev/compile_commands.json",
                        help="CMake database to read (default: %(default)s)")
    parser.add_argument("--out", default="build-clangd",
                        help="output directory (default: %(default)s)")
    parser.add_argument("--clang", default=None,
                        help="clang++ path (default: clang++ on PATH)")
    parser.add_argument("--cuda-path", default=os.environ.get("CUDA_PATH", ""),
                        help="CUDA toolkit root (default: $CUDA_PATH)")
    parser.add_argument("--gpu-arch", default="sm_86",
                        help="target parsed by clangd (default: %(default)s; "
                             "the dev GPU is an RTX 3050 Laptop)")
    args = parser.parse_args()

    base = (ROOT / args.base).resolve()
    if not base.exists():
        sys.exit(f"error: {base} not found - run: cmake --preset dev")

    clang = args.clang or shutil.which("clang++") or "clang++"
    cuda_path = args.cuda_path or "C:/Program Files/NVIDIA GPU Computing Toolkit/CUDA/v12.9"

    out = (ROOT / args.out).resolve()
    prelude_dir = out / "prelude"
    if out.exists():
        shutil.rmtree(out)
    prelude_dir.mkdir(parents=True)

    entries = json.loads(base.read_text())
    generated = []

    # .cu (and .cc promoted to CUDA by CMake): strip the nvcc command line,
    # keep includes/defines, parse as CUDA.
    for entry in entries:
        argv = split_command(entry)
        source = Path(entry["file"]).resolve()
        driver = Path(argv[0]).name.lower() if argv else ""
        is_cuda = source.suffix == ".cu" or "nvcc" in driver
        if is_cuda:
            generated.append({
                "directory": str(ROOT),
                "file": str(source),
                "arguments": clang_command(clang, cuda_path, args.gpu_arch,
                                           keep_includes(argv), source),
            })
        else:
            # MSVC cl.exe command: clangd understands it, keep it verbatim.
            generated.append({k: v for k, v in entry.items()
                              if k in ("directory", "file", "command", "arguments")})

    # Every library header: one command with its Requires: closure as prelude.
    for header in requires.ORDER:
        deps = [dep for dep in requires.ORDER if dep in requires.closure(header)]
        prelude = write_prelude(prelude_dir, header, deps)
        generated.append({
            "directory": str(ROOT),
            "file": str(ROOT / "csrc" / header),
            "arguments": clang_command(clang, cuda_path, args.gpu_arch,
                                       ["-include", str(prelude)],
                                       ROOT / "csrc" / header),
        })

    (out / "compile_commands.json").write_text(json.dumps(generated, indent=2) + "\n")
    print(f"wrote {len(generated)} entries "
          f"({len(requires.ORDER)} headers, {len(generated) - len(requires.ORDER)} TUs) "
          f"to {out / 'compile_commands.json'}")
    print(f"  clang++      {clang}")
    print(f"  cuda-path    {cuda_path}")
    print(f"  gpu-arch     {args.gpu_arch}")
    print("  restart clangd in the editor to pick it up")
    return 0


if __name__ == "__main__":
    sys.exit(main())
